init_multiple_sprites:
    ldy #0                       ; Y = sprite index (...SPRITE_COUNT-1)

sprite_loop:
    ; --------------------------------------------------------
    ; Copy 64 bytes from sprite_data_start + (Y * 64)
    ; into SPRITE_TARGET_RAM + (Y * 64)
    ; --------------------------------------------------------

    lda #<sprite_data_start
    sta src_ptr
    lda #>sprite_data_start
    sta src_ptr+1

    lda #<SPRITE_TARGET_RAM
    sta dst_ptr
    lda #>SPRITE_TARGET_RAM
    sta dst_ptr+1

    ; Apply Y * 64 offset to both pointers
    tya
    asl                         ; Y * 2
    asl                         ; Y * 4
    asl                         ; Y * 8
    asl                         ; Y * 16
    asl                         ; Y * 32
    asl                         ; Y * 64

    clc
    adc src_ptr
    sta src_ptr
    lda src_ptr+1
    adc #0
    sta src_ptr+1

    clc
    adc dst_ptr
    sta dst_ptr
    lda dst_ptr+1
    adc #0
    sta dst_ptr+1

    ; --------------------------------------------------------
    ; Copy loop: 64 bytes
    ; --------------------------------------------------------
    ldy #0
copy_spritebytes:
    lda (src_ptr),y
    sta (dst_ptr),y
    iny
    cpy #64
    bne copy_spritebytes

    ; --------------------------------------------------------
    ; Update VIC-II sprite pointer
    ; --------------------------------------------------------
    tya
    clc
    adc #SPRITE_VAL_PTR
    sta SPRITE_PTR_0,y

    ; Next sprite
    iny
    cpy #SPRITE_COUNT
    bne sprite_loop

    rts


